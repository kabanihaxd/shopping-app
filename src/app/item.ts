export type Item = {
  id: string;
  name: string;
  quantity: number;
  price: number;
  /** id категории из списка; '' — без категории (Firestore не принимает undefined) */
  categoryId: string;
  /** Когда куплен (мс). Есть только у купленных после появления статистики; Firestore не принимает undefined — поле просто отсутствует */
  boughtAt?: number;
  /** Товар перетащили вручную: он стоит на своём месте в группе, а остальные сортируются по цене вокруг него. Поля нет, если не закреплён. */
  pinned?: boolean;
  /** Заметка к товару: «без лактози», «бренд Х», «взяти велику упаковку». Поля нет, если заметки нет. */
  note?: string;
  /** Где куплен или где собираемся купить («Сільпо»). Поля нет, если не указан. */
  store?: string;
};

/** Сколько символов можно в заметке */
export const NOTE_MAX = 100;
/** Сколько символов можно в названии магазина */
export const STORE_MAX = 40;
